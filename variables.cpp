// simple C++ program to demonstrate the use of variables
#include<iostream>
using namespace std;
int main()
{
  
    // here we declared a variable called radius of type int
   
    int radius; 

    // here we assigned the value 6 to the variable radius
    
    radius = 6; 

   // here we declared a variable called pie of type float and assigned the value 3.14 to it
  
   float pie(3.14); 
  
   // here we declared a variable called area of type float
  
   float area; 
 
  // here we assigned the value of pie * radius * radius to the variable area
  
    area = pie * radius * radius; 
    
    // here we printed the value of area to the console
    cout << " the area of circle is: " << area; 


}

