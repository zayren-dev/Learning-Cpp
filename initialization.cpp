// simple C++ program to demonstrate the use of initialization
# include<iostream>
using namespace std;
int main()
{
    int number1 {56}; // here we declared a variable called number1 of type int and initialized it with the value 56
    int number2 {78}; // here we declared a variable called number2 of type int and initialized it with the value 78
    int sum {number1 + number2}; // here we declared a variable called sum of type int and initialized it with the value of number1 + number2
    cout<< " The sum of "<< number1 << " and " << number2 << " is: " << sum; // here we printed the value of sum to the console







}